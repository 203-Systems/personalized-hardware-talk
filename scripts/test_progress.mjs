import assert from 'node:assert/strict';
import {generateKeyPairSync,sign} from 'node:crypto';
import {readFileSync} from 'node:fs';
const source=readFileSync(new URL('../progress.js',import.meta.url),'utf8');
const {verifyProgress}=await import('data:text/javascript;base64,'+Buffer.from(source).toString('base64'));
const {privateKey,publicKey}=generateKeyPairSync('ed25519');
const jwk=publicKey.export({format:'jwk'});
const parent={id:'request-test-123456',version:'v5',slide:7};
const payload=Buffer.from(JSON.stringify({requestId:parent.id,version:'v5',slide:7,stage:'editing',detail:'正在调整网格',at:new Date().toISOString()}));
const envelope={type:'203-ai-progress/v1',payload:payload.toString('base64url'),signature:sign(null,payload,privateKey).toString('base64url')};
const reply={id:'reply-test-123456',created_at:Date.now(),content:JSON.stringify(envelope)};
assert.equal((await verifyProgress(reply,parent,jwk)).stage,'editing');
assert.equal(await verifyProgress(reply,{...parent,slide:8},jwk),null,'Progress cannot be replayed onto another slide');
assert.equal(await verifyProgress(reply,{...parent,id:'other'},jwk),null,'Progress must bind to its parent request');
assert.equal(await verifyProgress({...reply,content:JSON.stringify({...envelope,payload:Buffer.from(payload.toString().replace('editing','completed')).toString('base64url')})},parent,jwk),null,'Tampered progress must fail verification');
assert.equal(await verifyProgress(reply,parent,generateKeyPairSync('ed25519').publicKey.export({format:'jwk'})),null,'Wrong key must fail verification');
assert.equal(await verifyProgress({...reply,content:'普通匿名回复'},parent,jwk),null);
assert.equal(await verifyProgress(reply,parent,null),null);
console.log('Progress signatures: authentic, tampered, cross-request, cross-slide and wrong-key checks passed.');
